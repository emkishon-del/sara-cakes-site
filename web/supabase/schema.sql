-- ---------- who can edit ----------
-- The two admins (Sara and Mani). Add their emails at the bottom of this file.
create table if not exists public.admins (email text primary key);
alter table public.admins enable row level security;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins where lower(email) = lower(coalesce(auth.jwt() ->> 'email', '')));
$$;

-- ---------- content ----------
create table if not exists public.categories (
  slug text primary key,                 -- used in the URL: /catalog/<slug>/
  name text not null,
  blurb text default '',
  cover text,                            -- image stem of the cover photo (optional)
  sort int not null default 0,
  visible boolean not null default true
);

create table if not exists public.subcategories (
  category text not null references public.categories(slug),
  slug text not null,                    -- /catalog/<category>/<slug>/
  name text not null,
  sort int not null default 0,
  visible boolean not null default true,
  primary key (category, slug)
);

-- Work numbers are shown to customers and used in /cake/<id>/. An identity column never reuses a number,
-- even after a delete.
create table if not exists public.items (
  id int generated by default as identity primary key,
  category text not null references public.categories(slug),
  subcategory text,
  title text not null,
  caption text default '',
  alt text default '',
  image text not null,                   -- stem in the "images" bucket: <stem>.webp and <stem>-sm.webp
  sort int not null default 0,
  visible boolean not null default true,
  created_at timestamptz not null default now(),
  foreign key (category, subcategory) references public.subcategories(category, slug)
);
create index if not exists items_sort on public.items (sort);

create table if not exists public.reviews (
  id int generated by default as identity primary key,
  text text not null,
  tag text default '',
  sort int not null default 0,
  visible boolean not null default true
);

create table if not exists public.price_sections (
  id int generated by default as identity primary key,
  title text not null,
  sort int not null default 0
);
create table if not exists public.price_rows (
  id int generated by default as identity primary key,
  section_id int not null references public.price_sections(id) on delete cascade,
  name text not null,
  price text not null,
  unit text default '',
  sort int not null default 0
);

-- Small key/value settings: phone, wa_number, instagram, facebook, hero (array of 3 item ids),
-- hero_links (the three circles on the home page), prices_note.
create table if not exists public.settings (key text primary key, value jsonb not null);

-- Private: the Netlify build hook, used by the "publish" button. Not readable from the site.
create table if not exists public.private_config (key text primary key, value text not null);

-- ---------- access rules ----------
-- Visitors (and the site build) can read only what is visible. Only admins can change anything.
do $$
declare t text;
begin
  foreach t in array array['categories','subcategories','items','reviews','price_sections','price_rows','settings'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "public read" on public.%I', t);
    execute format('drop policy if exists "admin all" on public.%I', t);
    execute format('create policy "admin all" on public.%I for all to authenticated using (public.is_admin()) with check (public.is_admin())', t);
  end loop;
end $$;
create policy "public read" on public.categories    for select using (visible or public.is_admin());
create policy "public read" on public.subcategories for select using (visible or public.is_admin());
create policy "public read" on public.items         for select using (visible or public.is_admin());
create policy "public read" on public.reviews       for select using (visible or public.is_admin());
create policy "public read" on public.price_sections for select using (true);
create policy "public read" on public.price_rows     for select using (true);
create policy "public read" on public.settings       for select using (true);

alter table public.private_config enable row level security;   -- no policies: nobody reads it from outside
drop policy if exists "admins read self" on public.admins;
create policy "admins read self" on public.admins for select to authenticated using (lower(email) = lower(auth.jwt() ->> 'email'));

-- ---------- image storage ----------
insert into storage.buckets (id, name, public) values ('images', 'images', true)
on conflict (id) do update set public = true;
drop policy if exists "images admin insert" on storage.objects;
drop policy if exists "images admin update" on storage.objects;
drop policy if exists "images admin delete" on storage.objects;
create policy "images admin insert" on storage.objects for insert to authenticated with check (bucket_id = 'images' and public.is_admin());
create policy "images admin update" on storage.objects for update to authenticated using (bucket_id = 'images' and public.is_admin());
create policy "images admin delete" on storage.objects for delete to authenticated using (bucket_id = 'images' and public.is_admin());

-- ---------- "publish" button ----------
-- Calls the Netlify build hook so the site rebuilds with the latest changes (takes 1–2 minutes).
create extension if not exists pg_net with schema extensions;
create or replace function public.publish_site() returns text
language plpgsql security definer set search_path = public, extensions as $$
declare hook text;
begin
  if not public.is_admin() then raise exception 'not allowed'; end if;
  select value into hook from public.private_config where key = 'build_hook';
  if hook is null then return 'missing_hook'; end if;
  perform net.http_post(url := hook, body := '{}'::jsonb);
  return 'ok';
end $$;
revoke all on function public.publish_site() from public, anon;
grant execute on function public.publish_site() to authenticated;

-- Keeps new numbers after the highest existing ones (used once by scripts/seed.mjs after the import).
create or replace function public.sync_ids() returns void language plpgsql security definer set search_path = public as $$
begin
  perform setval(pg_get_serial_sequence('public.items','id'), greatest((select max(id) from public.items), 1));
  perform setval(pg_get_serial_sequence('public.reviews','id'), greatest((select max(id) from public.reviews), 1));
  perform setval(pg_get_serial_sequence('public.price_sections','id'), greatest((select max(id) from public.price_sections), 1));
end $$;
revoke all on function public.sync_ids() from public, anon, authenticated;

